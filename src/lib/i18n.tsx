type I18nValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey) => string;
  format: (key: TranslationKey, params: Record<string, string | number>) => string;
};
const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() =>
    localStorage.getItem('algoscope:locale') === 'ru' ? 'ru' : 'en',
  );
  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);
  function setLocale(next: Locale) {
    setLocaleState(next);
    localStorage.setItem('algoscope:locale', next);
    document.documentElement.lang = next;
  }
  const t = (key: TranslationKey) => translations[locale][key];
  const format = (key: TranslationKey, params: Record<string, string | number>) =>
    Object.entries(params).reduce<string>((text, [name, value]) => text.replaceAll(`{${name}}`, String(value)), t(key));
  return <I18nContext.Provider value={{ locale, setLocale, t, format }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error('useI18n must be used inside I18nProvider');
  return value;
}

