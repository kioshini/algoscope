export function localizeAlgorithm(algorithm: CatalogAlgorithmDefinition, locale: Locale): CatalogAlgorithmDefinition {
  if (locale === 'en') return algorithm;
  const copy = russianAlgorithmCopy[algorithm.id] ?? generatedRussianCopy(algorithm);
  const complexity = algorithm.complexity.note
    ? {
        ...algorithm.complexity,
        note:
          russianComplexityNotes[algorithm.id] ??
          'Оценка приведена для данной реализации и зависит от особенностей входных данных.',
      }
    : algorithm.complexity;
  return {
    ...algorithm,
    name: algorithmNames[algorithm.id] ?? algorithm.name,
    family: familyNames[algorithm.family] ?? algorithm.family,
    level: levelNames[algorithm.level] ?? algorithm.level,
    complexity,
    ...copy,
  } as CatalogAlgorithmDefinition;
}

